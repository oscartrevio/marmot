// Writes src/generated/mascot.ts: the marmot's frames, drawn by lib/mascot.sh through
// scripts/draw.sh so the site's marmot is the CLI's, and marmot's version from lib/core.sh.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

import { WIDTH } from "../src/lib/marmot.ts";
import type { Art, Frame, Ink, Mascot, Span } from "../src/lib/marmot.ts";

const ESC = "\u001B";
const INKS = new Set<string>([".", "d", "w", "e"]);
const BLINK: Record<Frame, number> = { blink: 1, open: 0, shut: 2 };

/** A row of draw.sh's output into spans: "\x1b<ink>" opens a run, "\x1b0" ends it. */
const spans = (row: string): Span[] => {
  const out: Span[] = [];
  let ink: Ink = ".";
  for (const [i, part] of row.split(ESC).entries()) {
    if (i > 0) {
      const next = part[0] === "0" ? "." : (part[0] ?? "");
      if (!INKS.has(next)) {
        throw new Error(
          `the marmot uses ink "${next}", which Art has no color for`
        );
      }
      ink = next as Ink;
    }
    const text = i > 0 ? part.slice(1) : part;
    if (text) {
      out.push([text, ink]);
    }
  }
  return out;
};

/** The happy marmot with its eyes `blink` (0 open, 1 half, 2 shut). */
const draw = async (blink: number): Promise<Art> => {
  const script = path.join(import.meta.dir, "draw.sh");
  const proc = Bun.spawn(
    ["bash", script, "happy", `${WIDTH}`, `${ESC}wmarmot${ESC}0`, `${blink}`],
    { stderr: "inherit" }
  );
  const [out, code] = await Promise.all([
    new Response(proc.stdout).text(),
    proc.exited,
  ]);
  if (code !== 0) {
    throw new Error(`draw.sh exited with ${code}`);
  }
  return out.split("\n").slice(0, -1).map(spans);
};

const frames = Object.keys(BLINK) as Frame[];
const drawn = await Promise.all(frames.map((f) => draw(BLINK[f])));
const mascot = Object.fromEntries(
  frames.map((f, i) => [f, drawn[i]])
) as Mascot;

/** The columns and rows of the drawing the favicon crops: the marmot, ears to paws. */
const ICON = { cols: [2, 16], rows: [0, 5] } as const;
const CELL = { h: 11, w: 6 };
const ICON_INK: Partial<Record<Ink, string>> = { d: "dim", e: "eye" };

/**
 * The marmot from `art` as a favicon: every character at its own column (as the README header
 * draws it, so no font can shift one), on no background, inked for the browser's light or dark
 * theme.
 */
const icon = (art: Art) => {
  const [c0, c1] = ICON.cols;
  const [r0, r1] = ICON.rows;
  const side = (c1 - c0) * CELL.w;
  const top = (side - (r1 - r0) * CELL.h) / 2;
  const rows = art.slice(r0, r1).map((row, r) => {
    let col = 0;
    const runs = row.flatMap(([text, ink]) => {
      const start = col;
      col += text.length;
      const chars = [...text]
        .map((ch, i) => [ch, start + i] as const)
        .filter(([ch, c]) => ch !== " " && c >= c0 && c < c1);
      if (chars.length === 0) {
        return [];
      }
      const xs = chars.map(([, c]) => (c - c0 + 0.5) * CELL.w).join(" ");
      const body = chars
        .map(([ch]) => ch)
        .join("")
        .replaceAll("&", "&amp;")
        .replaceAll("<", "&lt;");
      const cls = ICON_INK[ink] ? ` class="${ICON_INK[ink]}"` : "";
      return [`<tspan x="${xs}"${cls}>${body}</tspan>`];
    });
    const y = top + (r + 0.8) * CELL.h;
    return `<text y="${y}">${runs.join("")}</text>`;
  });
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${side} ${side}">
<style>
text{font:bold ${CELL.h}px ui-monospace,Menlo,"DejaVu Sans Mono",monospace;text-anchor:middle;paint-order:stroke;stroke-width:0.5;fill:#1c1c1c;stroke:#1c1c1c}
.dim{fill:#8b8b8b;stroke:#8b8b8b}
.eye{fill:#16a34a;stroke:#16a34a}
@media (prefers-color-scheme:dark){text{fill:#ededed;stroke:#ededed}.dim{fill:#9b9b9b;stroke:#9b9b9b}.eye{fill:#4ade80;stroke:#4ade80}}
</style>
${rows.join("\n")}
</svg>
`;
};

const core = await readFile(
  path.join(import.meta.dir, "../../../lib/core.sh"),
  "utf-8"
);
const version = core.match(/^MM_VERSION="(?<v>[^"]+)"/mu)?.groups?.v;
if (!version) {
  throw new Error("lib/core.sh sets no MM_VERSION");
}

const dir = path.join(import.meta.dir, "../src/generated");
await mkdir(dir, { recursive: true });
await writeFile(
  path.join(dir, "mascot.ts"),
  `// Generated by scripts/mascot.ts from lib/mascot.sh. Do not edit.\nimport type { Mascot } from "@/lib/marmot";\n\nexport const mascot: Mascot = ${JSON.stringify(mascot)};\n\nexport const version = ${JSON.stringify(version)};\n`
);
await writeFile(
  path.join(import.meta.dir, "../src/app/icon.svg"),
  icon(mascot.open)
);
